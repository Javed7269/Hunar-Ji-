    fun applyOverrides(
        base: LocalizedStrings,
        overrides: List<TranslationOverride>,
        langCode: String
    ): LocalizedStrings {
        val map = overrides
            .filter { it.languageCode.equals(langCode, ignoreCase = true) && it.value.isNotBlank() }
            .associate { it.key to it.value }
        if (map.isEmpty()) return base
        return base.copy(
            searchHint = map["searchHint"] ?: base.searchHint,
            bestDealsTitle = map["bestDealsTitle"] ?: base.bestDealsTitle,
            bestDealsSub = map["bestDealsSub"] ?: base.bestDealsSub,
            shopNow = map["shopNow"] ?: base.shopNow,
            specialOffers = map["specialOffers"] ?: base.specialOffers,
            liveServices = map["liveServices"] ?: base.liveServices,
            navHome = map["navHome"] ?: base.navHome,
            navCategories = map["navCategories"] ?: base.navCategories,
            navDeals = map["navDeals"] ?: base.navDeals,
            navWallet = map["navWallet"] ?: base.navWallet,
            navAccount = map["navAccount"] ?: base.navAccount,
            addToCart = map["addToCart"] ?: base.addToCart,
            bookNow = map["bookNow"] ?: base.bookNow,
            availableBalance = map["availableBalance"] ?: base.availableBalance,
            welcomeBack = map["welcomeBack"] ?: base.welcomeBack
        )
    }

